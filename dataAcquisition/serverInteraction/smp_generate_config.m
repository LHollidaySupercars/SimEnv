fprintf('Found %d valid plot rows.\n', height(T));

%% ── BUILD TAB/SUBTAB STRUCTURE ───────────────────────────────

% Get unique tabs preserving order of first appearance
tabs     = unique(string(T.Tab),    'stable');
subtabs  = unique(string(T.SubTab), 'stable');

% Build nested structure: tab -> {subtab -> [plots]}
% Use to_matlab_id (underscores) for struct field names
% Use to_js_id (hyphens) for JS output strings
tab_struct = struct();
for ti = 1:numel(tabs)
    tab    = tabs(ti);
    mat_id = to_matlab_id(tab);   % used as MATLAB struct key
    tab_rows = T(string(T.Tab) == tab, :);
    sub_list = unique(string(tab_rows.SubTab), 'stable');
    tab_struct.(mat_id).label    = tab;
    tab_struct.(mat_id).js_id    = to_js_id(tab);   % stored for JS output
    tab_struct.(mat_id).subtabs  = struct();
    for si = 1:numel(sub_list)
        sub     = sub_list(si);
        sub_mid = to_matlab_id(sub);   % MATLAB struct key
        sub_rows = tab_rows(string(tab_rows.SubTab) == sub, :);
        plots = build_plots(sub_rows);
        tab_struct.(mat_id).subtabs.(sub_mid).label  = sub;
        tab_struct.(mat_id).subtabs.(sub_mid).js_id  = to_js_id(sub);
        tab_struct.(mat_id).subtabs.(sub_mid).plots  = plots;
    end
end

